import { join, relative } from 'node:path'

import { uniq } from 'massaman/array'

import type { LockedPack, LockedPreset, Lockfile } from '../project/lock.js'
import { buildContentDestination } from './destination.js'
import { hashContent } from './integrity.js'
import type { FileChange } from './plan.js'

/**
 * Build navigation changes without overwriting unrelated indexes.
 */
export function buildIndexChanges({
  lock,
  previous,
}: {
  readonly lock: Lockfile
  readonly previous: Lockfile
}): readonly FileChange[] {
  return uniq(lock.packs.map((pack) => pack.output)).map((output) => ({
    path: join(output, 'INDEX.md'),
    content: renderContextIndex({ lock, output }),
    expected: getPreviousIndexHash({ previous, output }),
    expectedAlternatives: [
      hashContent(legacyIndexLinks(renderContextIndex({ lock: previous, output }))),
    ],
  }))
}

/**
 * Render entrypoint links for one installation root.
 */
export function renderContextIndex({
  lock,
  output,
}: {
  readonly lock: Lockfile
  readonly output: string
}): string {
  const lines = lock.packs
    .filter((pack) => pack.output === output)
    .flatMap((pack) =>
      pack.groups.map((group) => {
        return `- ${renderEntryLink({ output, pack, group })}`
      })
    )
  const presets = (lock.presets ?? []).filter((preset) =>
    preset.members.some((member) =>
      lock.packs.some((pack) => pack.request.name === member.name && pack.output === output)
    )
  )
  if (!presets.length) {
    return `# Granary context\n\nGenerated by Granary. Read the selected entrypoint before searching its files.\n\n${lines.join('\n')}\n`
  }
  const recommended = presets.map((preset) => renderPreset({ preset, lock, output })).join('\n\n')
  return `# Granary context\n\nGenerated by Granary. Read the selected entrypoint before searching its files.\n\n## Recommended sets\n\n${recommended}\n\n## Component packs\n\n${lines.join('\n')}\n`
}

/**
 * @private
 */
type RenderEntryLinkParams = {
  readonly output: string
  readonly pack: LockedPack
  readonly group: LockedPack['groups'][number]
}

/**
 * @private
 */
function renderEntryLink({ output, pack, group }: RenderEntryLinkParams): string {
  const entry = relative(output, buildContentDestination({ pack, group, path: group.entry }))
    .split('\\')
    .join('/')
  const target = indexLinkTarget(entry)
  return `**${pack.request.name}@${pack.version}** (${group.name}): [${group.entry}](${target})`
}

/**
 * @private
 */
function indexLinkTarget(entry: string): string {
  if (/[\s()<>]/.test(entry)) {
    return `<${entry}>`
  }
  return entry
}

/**
 * @private
 */
function legacyIndexLinks(content: string): string {
  return content.replace(/\]\(([^\s<>()[\]]+)\)/g, '](<$1>)')
}

/**
 * @private
 */
type RenderPresetParams = {
  readonly preset: LockedPreset
  readonly lock: Lockfile
  readonly output: string
}

/**
 * @private
 */
function renderPreset({ preset, lock, output }: RenderPresetParams): string {
  const members = preset.members.flatMap((member) => {
    const pack = lock.packs.find((entry) => entry.request.name === member.name)
    if (!pack) {
      return []
    }
    return pack.groups.map((group) => renderEntryLink({ output, pack, group }))
  })
  return `### ${preset.request.name}@${preset.version}\n\nRead these components in order. Language-specific rules apply only to their language.\n\n${members.map((line, index) => `${index + 1}. ${line}`).join('\n')}`
}

/**
 * @private
 */
function getPreviousIndexHash({
  previous,
  output,
}: {
  readonly previous: Lockfile
  readonly output: string
}): string | undefined {
  if (!previous.packs.some((pack) => pack.output === output)) {
    return undefined
  }
  return hashContent(renderContextIndex({ lock: previous, output }))
}
